"""
Write the OpenFOAM dictionaries for the plunging NACA 0009.

Two cases share the mesh:
  steady/    simpleFoam, static airfoil, gives the initial field
  unsteady/  pimpleFoam, whole mesh oscillating as y = A sin(2 pi f t)

usage: python3 setup_case.py <caseDir> <steady|unsteady> <nProcs> [maxCycles]
"""
import os
import sys

import params as P

HDR = """/*--------------------------------*- C++ -*----------------------------------*\\
  Plunging NACA 0009 - generated by scripts/setup_case.py
\\*---------------------------------------------------------------------------*/
FoamFile
{
    version     2.0;
    format      ascii;
    class       %s;
    location    "%s";
    object      %s;
}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //

"""


def write(case, loc, name, body, cls="dictionary"):
    d = os.path.join(case, loc)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, name), "w") as f:
        f.write(HDR % (cls, loc, name) + body)


def field(case, name, cls, dim, internal, bcs):
    body = "dimensions      %s;\n\ninternalField   %s;\n\nboundaryField\n{\n" % (dim, internal)
    for patch, bc in bcs.items():
        body += "    %s\n    {\n" % patch
        for line in bc.strip().split("\n"):
            body += "        %s\n" % line.strip()
        body += "    }\n"
    body += "}\n"
    write(case, "0", name, body, cls)


def zero(case, moving):
    U = "uniform (%.6g 0 0)" % P.U_INF

    def bcs(far, out, wall):
        return {"farfield": far, "outlet": out, "airfoil": wall, "frontAndBack": "type empty;"}

    field(case, "U", "volVectorField", "[0 1 -1 0 0 0 0]", U, bcs(
        "type freestreamVelocity;\nfreestreamValue %s;\nvalue %s;" % (U, U),
        "type inletOutlet;\ninletValue %s;\nvalue %s;" % (U, U),
        "type movingWallVelocity;\nvalue uniform (0 0 0);" if moving else "type noSlip;"))
    field(case, "p", "volScalarField", "[0 2 -2 0 0 0 0]", "uniform 0", bcs(
        "type freestreamPressure;\nfreestreamValue uniform 0;\nvalue uniform 0;",
        "type fixedValue;\nvalue uniform 0;",
        "type zeroGradient;"))

    def scalar(name, dim, val, wall):
        v = "uniform %.6g" % val
        field(case, name, "volScalarField", dim, v, bcs(
            "type inletOutlet;\ninletValue %s;\nvalue %s;" % (v, v),
            "type inletOutlet;\ninletValue %s;\nvalue %s;" % (v, v), wall))

    scalar("k", "[0 2 -2 0 0 0 0]", P.K_INF, "type fixedValue;\nvalue uniform 1e-14;")
    scalar("omega", "[0 0 -1 0 0 0 0]", P.OMEGA_INF,
           "type omegaWallFunction;\nvalue uniform %.6g;" % P.OMEGA_INF)
    scalar("ReThetat", "[0 0 0 0 0 0 0]", P.RETHETA_INF, "type zeroGradient;")
    scalar("gammaInt", "[0 0 0 0 0 0 0]", 1.0, "type zeroGradient;")
    field(case, "nut", "volScalarField", "[0 2 -1 0 0 0 0]", "uniform %.6g" % P.NUT_INF, bcs(
        "type calculated;\nvalue uniform %.6g;" % P.NUT_INF,
        "type calculated;\nvalue uniform %.6g;" % P.NUT_INF,
        "type nutLowReWallFunction;\nvalue uniform 0;"))


def constant(case, moving, max_cycles=P.MAX_CYCLES):
    write(case, "constant", "transportProperties",
          "transportModel  Newtonian;\n\nnu              %.6g;\n" % P.NU)
    write(case, "constant", "turbulenceProperties", """simulationType  RAS;

RAS
{
    RASModel        kOmegaSSTLM;    // k-omega SST + gamma-ReTheta_t transition (Langtry-Menter)
    turbulence      on;
    printCoeffs     on;

    kOmegaSSTLMCoeffs
    {
        decayControl    yes;        // keep the free-stream turbulence level
        kInf            %.6g;
        omegaInf        %.6g;
    }
}
""" % (P.K_INF, P.OMEGA_INF))
    if moving:
        # rigid plunge of the whole mesh, y(t) = A r(t) sin(omega t), given as a
        # table with one entry per time step (the ramp r avoids an impulsive start)
        n = int(round((max_cycles + 1) * P.STEPS_PER_CYCLE)) + 1
        rows = []
        for k in range(n):
            t = k * P.DT
            rows.append("(%.10g ((0 %.10g 0) (0 0 0)))" % (t, P.plunge(t)[0]))
        with open(os.path.join(case, "constant", "plunge.dat"), "w") as f:
            f.write("// time  ((dx dy dz) (rx ry rz))   y = A r(t) sin(omega t)\n%d\n(\n%s\n)\n"
                    % (n, "\n".join(rows)))
        write(case, "constant", "dynamicMeshDict", """// rigid plunge of the whole mesh:  y(t) = A r(t) sin(omega t)
//   A = %.4g m, f = %.4g Hz, r = smooth ramp over the first %.4g s
dynamicFvMesh       dynamicMotionSolverFvMesh;
motionSolverLibs    (fvMotionSolvers);
motionSolver        solidBody;

solidBodyMotionFunction tabulated6DoFMotion;
CofG                (%.6g 0 0);
timeDataFileName    "<constant>/plunge.dat";

tabulated6DoFMotionCoeffs
{
    CofG                (%.6g 0 0);
    timeDataFileName    "<constant>/plunge.dat";
}
""" % (P.AMP, P.FREQ, P.RAMP_TIME, P.X_LE + 0.25 * P.C, P.X_LE + 0.25 * P.C))


def functions(steady):
    every = "timeStep;\n        writeInterval   1"
    fo = """    coeffs
    {
        type            forceCoeffs;
        libs            ("libforces.so");
        writeControl    %s;
        log             false;
        patches         (airfoil);
        rho             rhoInf;
        rhoInf          %.6g;
        liftDir         (0 1 0);
        dragDir         (1 0 0);
        CofR            (%.6g 0 0);     // c/4 of the airfoil at y = 0 (corrected for the plunge in post)
        pitchAxis       (0 0 -1);       // positive = nose-up
        magUInf         %.6g;
        lRef            %.6g;
        Aref            %.6g;
    }
""" % (every, P.RHO, P.X_LE + 0.25 * P.C, P.U_INF, P.C, P.C * P.SPAN)
    if not steady:
        fo += """    yPlus
    {
        type            yPlus;
        libs            ("libfieldFunctionObjects.so");
        writeControl    writeTime;
    }
    wallShearStress
    {
        type            wallShearStress;
        libs            ("libfieldFunctionObjects.so");
        patches         (airfoil);
        writeControl    writeTime;
    }
"""
    return fo


def system(case, steady, nprocs, max_cycles):
    if steady:
        write(case, "system", "controlDict", """application     simpleFoam;
startFrom       latestTime;
startTime       0;
stopAt          endTime;
endTime         %d;
deltaT          1;
writeControl    timeStep;
writeInterval   %d;
purgeWrite      1;
writeFormat     ascii;
writePrecision  10;
writeCompression off;
timeFormat      general;
timePrecision   6;
runTimeModifiable true;

functions
{
%s}
""" % (P.STEADY_ITER, P.STEADY_ITER, functions(True)))
    else:
        write(case, "system", "controlDict", """application     pimpleFoam;
startFrom       latestTime;
startTime       0;
stopAt          endTime;
endTime         %.10g;          // %d cycles of T = %.6g s
deltaT          %.10g;          // %d steps per cycle

writeControl    timeStep;
writeInterval   %d;             // %d snapshots per cycle
purgeWrite      %d;             // keep the last cycle only
writeFormat     ascii;
writePrecision  8;
writeCompression off;
timeFormat      general;
timePrecision   10;
runTimeModifiable true;
adjustTimeStep  no;

functions
{
%s}
""" % (max_cycles * P.PERIOD, max_cycles, P.PERIOD, P.DT, P.STEPS_PER_CYCLE,
           P.STEPS_PER_CYCLE // P.SNAPSHOTS_PER_CYCLE, P.SNAPSHOTS_PER_CYCLE,
           P.SNAPSHOTS_PER_CYCLE, functions(False)))

    write(case, "system", "fvSchemes", """ddtSchemes
{
    default         %s;
}

gradSchemes
{
    default         cellLimited Gauss linear 1;
}

divSchemes
{
    default         none;
    div(phi,U)      bounded Gauss linearUpwind grad(U);
    div(phi,k)      bounded Gauss limitedLinear 1;
    div(phi,omega)  bounded Gauss limitedLinear 1;
    div(phi,ReThetat) bounded Gauss limitedLinear 1;
    div(phi,gammaInt) bounded Gauss limitedLinear 1;
    div((nuEff*dev2(T(grad(U))))) Gauss linear;
}

laplacianSchemes
{
    default         Gauss linear limited corrected 0.5;
}

interpolationSchemes
{
    default         linear;
}

snGradSchemes
{
    default         limited corrected 0.5;
}

wallDist
{
    method          meshWave;
    updateInterval  1000000;        // rigid motion: wall distance does not change
}
""" % ("steadyState" if steady else "backward"))

    if steady:
        algo = """SIMPLE
{
    consistent      yes;
    nNonOrthogonalCorrectors 1;
}

relaxationFactors
{
    equations
    {
        U               0.9;
        "(k|omega)"     0.8;
        "(ReThetat|gammaInt)" 0.8;
    }
}
"""
    else:
        algo = """PIMPLE
{
    momentumPredictor yes;
    nOuterCorrectors %d;
    nCorrectors     2;
    nNonOrthogonalCorrectors 1;
    correctPhi      no;             // rigid translation: no flux correction needed
    moveMeshOuterCorrectors no;
}

relaxationFactors
{
    fields
    {
        p               %g;
        pFinal          1;
    }
    equations
    {
        "(U|k|omega|ReThetat|gammaInt)" %g;
        "(U|k|omega|ReThetat|gammaInt)Final" 1;
    }
}
""" % (P.N_OUTER, P.RELAX_P, P.RELAX_EQ)
    write(case, "system", "fvSolution", """solvers
{
    p
    {
        solver          GAMG;
        smoother        GaussSeidel;
        tolerance       1e-7;
        relTol          0.05;
    }
    pFinal
    {
        $p;
        tolerance       1e-8;
        relTol          0.001;
    }
    "(U|k|omega|ReThetat|gammaInt)"
    {
        solver          smoothSolver;
        smoother        symGaussSeidel;
        tolerance       1e-9;
        relTol          0.1;
    }
    "(U|k|omega|ReThetat|gammaInt)Final"
    {
        solver          smoothSolver;
        smoother        symGaussSeidel;
        tolerance       1e-9;
        relTol          0.01;
    }
}

%s""" % algo)
    write(case, "system", "decomposeParDict", "numberOfSubdomains %d;\n\nmethod          scotch;\n"
          % nprocs)


if __name__ == "__main__":
    case, stage = sys.argv[1], sys.argv[2]
    nprocs = int(sys.argv[3]) if len(sys.argv) > 3 else P.N_PROCS
    max_cycles = int(sys.argv[4]) if len(sys.argv) > 4 else P.MAX_CYCLES
    steady = stage == "steady"
    zero(case, moving=not steady)
    constant(case, moving=not steady, max_cycles=max_cycles)
    system(case, steady, nprocs, max_cycles)
    print("%s case dictionaries written to %s" % (stage, case))
